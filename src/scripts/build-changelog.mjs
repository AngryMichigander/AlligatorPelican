#!/usr/bin/env node
/**
 * build-changelog.mjs
 * Reads git log for changes to sources.json and counter-inputs.json,
 * then emits src/pages/changelog.astro.
 * Safe to run on a fresh repo with 1 commit (outputs a stub page).
 */

import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');

/** Parse `git log --follow --patch` output into structured entries */
function parseGitLog(raw) {
  if (!raw.trim()) return [];

  const entries = [];
  // Split on commit boundaries
  const commitPattern = /^commit ([0-9a-f]{40})/m;
  const blocks = raw.split(/(?=^commit [0-9a-f]{40})/m);

  for (const block of blocks) {
    if (!block.trim()) continue;
    const hashMatch = block.match(/^commit ([0-9a-f]{7})[0-9a-f]*/m);
    const dateMatch = block.match(/^Date:\s+(.+)$/m);
    const msgMatch = block.match(/^    (.+)$/m);

    if (!hashMatch || !dateMatch || !msgMatch) continue;

    const hash = hashMatch[1];
    const date = new Date(dateMatch[1].trim()).toISOString().slice(0, 10);
    const message = msgMatch[1].trim();

    // Count added/removed lines from the diff
    const additions = (block.match(/^\+[^+]/gm) || []).length;
    const deletions = (block.match(/^-[^-]/gm) || []).length;

    entries.push({ hash, date, message, additions, deletions });
  }

  return entries;
}

/** Escape HTML special chars for safe embedding in Astro template */
function esc(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function main() {
  let raw = '';
  try {
    raw = execSync(
      'git log --follow --patch -- src/data/sources.json src/data/counter-inputs.json',
      { cwd: ROOT, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }
    );
  } catch (err) {
    // Git not available or no history — safe fallback
    raw = '';
  }

  const entries = parseGitLog(raw);

  let content;

  if (entries.length === 0) {
    content = `---
// Auto-generated by src/scripts/build-changelog.mjs — do not edit by hand.
const title = "Changelog";
---
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>{title} — AlligatorPelican</title>
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
  </head>
  <body>
    <main>
      <h1>Changelog</h1>
      <p>No source or counter-input changes recorded yet. This page will populate automatically as <code>sources.json</code> and <code>counter-inputs.json</code> are updated.</p>
      <p><a href="/">← Back to home</a></p>
    </main>
  </body>
</html>
`;
  } else {
    const rows = entries
      .map(
        ({ hash, date, message, additions, deletions }) =>
          `      <li class="changelog-entry">
        <time datetime="${esc(date)}">${esc(date)}</time>
        <code class="hash">${esc(hash)}</code>
        <span class="message">${esc(message)}</span>
        <span class="diff-stat">+${additions} -${deletions}</span>
      </li>`
      )
      .join('\n');

    content = `---
// Auto-generated by src/scripts/build-changelog.mjs — do not edit by hand.
const title = "Changelog";
const entries = ${JSON.stringify(entries, null, 2)};
---
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>{title} — AlligatorPelican</title>
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
  </head>
  <body>
    <main>
      <h1>Changelog</h1>
      <p>All commits that modified <code>sources.json</code> or <code>counter-inputs.json</code>, newest first.</p>
      <ul class="changelog-list">
${rows}
      </ul>
      <p><a href="/">← Back to home</a></p>
    </main>
  </body>
</html>
`;
  }

  const outPath = join(ROOT, 'src', 'pages', 'changelog.astro');
  writeFileSync(outPath, content, 'utf8');
  console.log(`[build-changelog] wrote ${outPath} (${entries.length} entries)`);
}

main();
